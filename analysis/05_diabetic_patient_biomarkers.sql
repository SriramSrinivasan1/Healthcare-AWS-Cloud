/*
==============================================================
Query 5: Diabetic Patient Biomarker Profile (Outreach List)
--------------------------------------------------------------
Question: Which diabetic patients need follow-up?
Purpose:  Lists every patient with a diabetes diagnosis alongside
          their average HbA1c and BMI, so patients above the
          6.5% HbA1c threshold, or with no HbA1c on record,
          can be prioritized for outreach.
Tables:   dim_patients, fact_conditions, fact_lab_results
Result:   05_diabetic_patient_biomarkers.csv
Note:     All patient names are synthetic (generated by Synthea).
==============================================================
*/

SELECT 
    p.patient_name,
    p.gender,
    p.age_years,
    l.test_name,
    ROUND(AVG(l.value), 2) AS avg_biomarker,
    l.unit
FROM dim_patients p
JOIN fact_conditions c ON p.patient_id = c.patient_id
JOIN fact_lab_results l ON p.patient_id = l.patient_id
WHERE LOWER(c.condition) LIKE '%diabetes%'
  AND (LOWER(l.test_name) LIKE '%hemoglobin a1c%' OR LOWER(l.test_name) LIKE '%body mass index%')
-- Includes p.patient_id in GROUP BY so distinct patients sharing identical names do not merge
GROUP BY p.patient_id, p.patient_name, p.gender, p.age_years, l.test_name, l.unit
ORDER BY p.patient_name, l.test_name;
